/*
 * System-wide macro playback engine and low-level mouse hook for Windows.
 * Intercepts bound mouse button clicks and reproduces macro keystroke/click sequences via SendInput.
 */

#![allow(dead_code, non_snake_case, non_camel_case_types)]

use crate::state::MacroItem;
#[cfg(windows)]
use crate::state::{MacroStep, MacroTriggerMode};
use std::collections::HashMap;
#[cfg(windows)]
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{Arc, OnceLock, RwLock};

pub const MACRO_TAG: usize = 0x4D414352; /* 'MACR' tag for SendInput extraInfo */

static GLOBAL_BINDINGS: OnceLock<Arc<RwLock<HashMap<usize, MacroItem>>>> = OnceLock::new();

pub fn get_global_macro_bindings() -> Arc<RwLock<HashMap<usize, MacroItem>>> {
    GLOBAL_BINDINGS
        .get_or_init(|| Arc::new(RwLock::new(HashMap::new())))
        .clone()
}

#[cfg(not(windows))]
pub fn start_mouse_macro_hook() {
    /* Background software mouse hooking is Windows-specific; Linux uses hardware macros */
}

#[cfg(not(windows))]
pub fn play_macro(_item: &MacroItem) {
    /* Linux macro execution is programmed directly into onboard mouse memory */
}

#[cfg(windows)]
pub use windows_impl::*;

#[cfg(windows)]
mod windows_impl {
    use super::*;

    /* Win32 types & constants */
    const WH_MOUSE_LL: i32 = 14;
    const WM_RBUTTONDOWN: usize = 0x0204;
    const WM_RBUTTONUP: usize = 0x0205;
    const WM_MBUTTONDOWN: usize = 0x0207;
    const WM_MBUTTONUP: usize = 0x0208;
    const WM_XBUTTONDOWN: usize = 0x020B;
    const WM_XBUTTONUP: usize = 0x020C;

    static ACTIVE_HOLDS: OnceLock<Arc<RwLock<HashMap<usize, Arc<AtomicBool>>>>> = OnceLock::new();
    static TOGGLE_STATES: OnceLock<Arc<RwLock<HashMap<usize, Arc<AtomicBool>>>>> = OnceLock::new();

    fn get_active_holds() -> Arc<RwLock<HashMap<usize, Arc<AtomicBool>>>> {
        ACTIVE_HOLDS.get_or_init(|| Arc::new(RwLock::new(HashMap::new()))).clone()
    }

    fn get_toggle_states() -> Arc<RwLock<HashMap<usize, Arc<AtomicBool>>>> {
        TOGGLE_STATES.get_or_init(|| Arc::new(RwLock::new(HashMap::new()))).clone()
    }

    const XBUTTON1: u16 = 1; /* Back (Button 3) */
    const XBUTTON2: u16 = 2; /* Advance (Button 4) */

    const INPUT_MOUSE: u32 = 0;
    const INPUT_KEYBOARD: u32 = 1;

    const KEYEVENTF_KEYUP: u32 = 0x0002;
    const MOUSEEVENTF_LEFTDOWN: u32 = 0x0002;
    const MOUSEEVENTF_LEFTUP: u32 = 0x0004;
    const MOUSEEVENTF_RIGHTDOWN: u32 = 0x0008;
    const MOUSEEVENTF_RIGHTUP: u32 = 0x0010;
    const MOUSEEVENTF_MIDDLEDOWN: u32 = 0x0020;
    const MOUSEEVENTF_MIDDLEUP: u32 = 0x0040;

    #[repr(C)]
    #[derive(Clone, Copy)]
    struct POINT {
        x: i32,
        y: i32,
    }

    #[repr(C)]
    #[derive(Clone, Copy)]
    struct MSLLHOOKSTRUCT {
        pt: POINT,
        mouseData: u32,
        flags: u32,
        time: u32,
        dwExtraInfo: usize,
    }

    #[repr(C)]
    struct MSG {
        hwnd: *mut std::ffi::c_void,
        message: u32,
        wParam: usize,
        lParam: isize,
        time: u32,
        pt: POINT,
    }

    #[repr(C)]
    struct INPUT {
        r#type: u32,
        u: INPUT_UNION,
    }

    #[repr(C)]
    union INPUT_UNION {
        ki: KEYBDINPUT,
        mi: MOUSEINPUT,
    }

    #[repr(C)]
    #[derive(Clone, Copy)]
    struct KEYBDINPUT {
        wVk: u16,
        wScan: u16,
        dwFlags: u32,
        time: u32,
        dwExtraInfo: usize,
    }

    #[repr(C)]
    #[derive(Clone, Copy)]
    struct MOUSEINPUT {
        dx: i32,
        dy: i32,
        mouseData: u32,
        dwFlags: u32,
        time: u32,
        dwExtraInfo: usize,
    }

    extern "system" {
        fn SetWindowsHookExW(
            idHook: i32,
            lpfn: unsafe extern "system" fn(i32, usize, isize) -> isize,
            hmod: *mut std::ffi::c_void,
            dwThreadId: u32,
        ) -> *mut std::ffi::c_void;

        fn UnhookWindowsHookEx(hhk: *mut std::ffi::c_void) -> i32;

        fn CallNextHookEx(
            hhk: *mut std::ffi::c_void,
            nCode: i32,
            wParam: usize,
            lParam: isize,
        ) -> isize;

        fn GetMessageW(
            lpMsg: *mut std::ffi::c_void,
            hWnd: *mut std::ffi::c_void,
            wMsgFilterMin: u32,
            wMsgFilterMax: u32,
        ) -> i32;

        fn TranslateMessage(lpMsg: *const std::ffi::c_void) -> i32;
        fn DispatchMessageW(lpMsg: *const std::ffi::c_void) -> isize;

        fn SendInput(cInputs: u32, pInputs: *const INPUT, cbSize: i32) -> u32;

        fn GetModuleHandleW(lpModuleName: *const u16) -> *mut std::ffi::c_void;
    }

    unsafe extern "system" fn mouse_hook_proc(nCode: i32, wParam: usize, lParam: isize) -> isize {
        if nCode >= 0 {
            let ms = *(lParam as *const MSLLHOOKSTRUCT);
            /* Pass through inputs generated by our own macro playback to prevent recursion */
            if ms.dwExtraInfo == MACRO_TAG {
                return CallNextHookEx(std::ptr::null_mut(), nCode, wParam, lParam);
            }

            let (btn_idx, is_down) = match wParam {
                WM_XBUTTONDOWN | WM_XBUTTONUP => {
                    let xbtn = (ms.mouseData >> 16) as u16;
                    let idx = if xbtn == XBUTTON1 {
                        Some(3) /* Back button */
                    } else if xbtn == XBUTTON2 {
                        Some(4) /* Advance / Forward button */
                    } else {
                        None
                    };
                    (idx, wParam == WM_XBUTTONDOWN)
                }
                WM_MBUTTONDOWN | WM_MBUTTONUP => (Some(2), wParam == WM_MBUTTONDOWN),
                WM_RBUTTONDOWN | WM_RBUTTONUP => (Some(1), wParam == WM_RBUTTONDOWN),
                _ => (None, false),
            };

            if let Some(idx) = btn_idx {
                if is_down {
                    let macro_to_play = {
                        let bindings = get_global_macro_bindings();
                        let guard = bindings.read().ok();
                        guard.and_then(|g| g.get(&idx).cloned())
                    };

                    if let Some(macro_item) = macro_to_play {
                        match macro_item.trigger_mode {
                            MacroTriggerMode::Once => {
                                std::thread::spawn(move || {
                                    play_macro(&macro_item);
                                });
                            }
                            MacroTriggerMode::HoldToRepeat => {
                                let flag = Arc::new(AtomicBool::new(true));
                                if let Ok(mut holds) = get_active_holds().write() {
                                    holds.insert(idx, flag.clone());
                                }
                                let f = flag.clone();
                                std::thread::spawn(move || {
                                    while f.load(Ordering::SeqCst) {
                                        play_macro_once(&macro_item);
                                        std::thread::sleep(std::time::Duration::from_millis(5));
                                    }
                                });
                            }
                            MacroTriggerMode::Toggle => {
                                if let Ok(mut guard) = get_toggle_states().write() {
                                    if let Some(existing) = guard.remove(&idx) {
                                        existing.store(false, Ordering::SeqCst);
                                    } else {
                                        let flag = Arc::new(AtomicBool::new(true));
                                        guard.insert(idx, flag.clone());
                                        let f = flag.clone();
                                        std::thread::spawn(move || {
                                            while f.load(Ordering::SeqCst) {
                                                play_macro_once(&macro_item);
                                                std::thread::sleep(std::time::Duration::from_millis(5));
                                            }
                                        });
                                    }
                                }
                            }
                        }
                        /* Suppress original button down event so the macro fires cleanly */
                        return 1;
                    }
                } else {
                    /* Button released (UP): terminate active hold for this button */
                    if let Ok(mut holds) = get_active_holds().write() {
                        if let Some(flag) = holds.remove(&idx) {
                            flag.store(false, Ordering::SeqCst);
                            return 1;
                        }
                    }
                }
            }
        }

        CallNextHookEx(std::ptr::null_mut(), nCode, wParam, lParam)
    }

    /* Spawns the global low-level Windows mouse hook thread */
    pub fn start_mouse_macro_hook() {
        std::thread::spawn(|| unsafe {
            let hook = SetWindowsHookExW(
                WH_MOUSE_LL,
                mouse_hook_proc,
                GetModuleHandleW(std::ptr::null()),
                0,
            );

            if hook.is_null() {
                return;
            }

            let mut msg = std::mem::zeroed();
            while GetMessageW(&mut msg as *mut _ as *mut std::ffi::c_void, std::ptr::null_mut(), 0, 0) > 0 {
                TranslateMessage(&msg as *const _ as *const std::ffi::c_void);
                DispatchMessageW(&msg as *const _ as *const std::ffi::c_void);
            }

            UnhookWindowsHookEx(hook);
        });
    }

    /* Plays a macro sequence repeated times using Windows SendInput */
    pub fn play_macro(item: &MacroItem) {
        let repeats = item.repeat_count.max(1);
        for _ in 0..repeats {
            play_macro_once(item);
        }
    }

    /* Executes a single iteration of a macro sequence */
    pub fn play_macro_once(item: &MacroItem) {
        for step in &item.steps {
            match step {
                MacroStep::KeyDown(k) => {
                    if let Some(vk) = key_to_vk(k) {
                        send_key_event(vk, true);
                    }
                }
                MacroStep::KeyUp(k) => {
                    if let Some(vk) = key_to_vk(k) {
                        send_key_event(vk, false);
                    }
                }
                MacroStep::KeyPress(k) => {
                    if let Some(vk) = key_to_vk(k) {
                        send_key_event(vk, true);
                        std::thread::sleep(std::time::Duration::from_millis(20));
                        send_key_event(vk, false);
                    }
                }
                MacroStep::MouseDown(b) => {
                    send_mouse_event(b, true);
                }
                MacroStep::MouseUp(b) => {
                    send_mouse_event(b, false);
                }
                MacroStep::DelayMs(ms) => {
                    std::thread::sleep(std::time::Duration::from_millis(*ms as u64));
                }
            }
        }
    }

    fn send_key_event(vk: u16, is_down: bool) {
        let flags = if is_down { 0 } else { KEYEVENTF_KEYUP };
        let input = INPUT {
            r#type: INPUT_KEYBOARD,
            u: INPUT_UNION {
                ki: KEYBDINPUT {
                    wVk: vk,
                    wScan: 0,
                    dwFlags: flags,
                    time: 0,
                    dwExtraInfo: MACRO_TAG,
                },
            },
        };
        unsafe {
            SendInput(1, &input, std::mem::size_of::<INPUT>() as i32);
        }
    }

    fn send_mouse_event(btn: &str, is_down: bool) {
        let flag = match btn.to_lowercase().as_str() {
            "left" => {
                if is_down {
                    MOUSEEVENTF_LEFTDOWN
                } else {
                    MOUSEEVENTF_LEFTUP
                }
            }
            "right" => {
                if is_down {
                    MOUSEEVENTF_RIGHTDOWN
                } else {
                    MOUSEEVENTF_RIGHTUP
                }
            }
            "middle" => {
                if is_down {
                    MOUSEEVENTF_MIDDLEDOWN
                } else {
                    MOUSEEVENTF_MIDDLEUP
                }
            }
            _ => {
                if is_down {
                    MOUSEEVENTF_LEFTDOWN
                } else {
                    MOUSEEVENTF_LEFTUP
                }
            }
        };

        let input = INPUT {
            r#type: INPUT_MOUSE,
            u: INPUT_UNION {
                mi: MOUSEINPUT {
                    dx: 0,
                    dy: 0,
                    mouseData: 0,
                    dwFlags: flag,
                    time: 0,
                    dwExtraInfo: MACRO_TAG,
                },
            },
        };
        unsafe {
            SendInput(1, &input, std::mem::size_of::<INPUT>() as i32);
        }
    }

    /* Converts human key label into a Windows Virtual Key code */
    fn key_to_vk(key_name: &str) -> Option<u16> {
        let trimmed = key_name.trim();
        if trimmed.is_empty() {
            return None;
        }

        /* Single character (A-Z, 0-9) */
        if trimmed.len() == 1 {
            let ch = trimmed.chars().next().unwrap().to_ascii_uppercase();
            if ch.is_ascii_alphanumeric() {
                return Some(ch as u16);
            }
        }

        match trimmed.to_lowercase().as_str() {
            "space" => Some(0x20),
            "enter" | "return" => Some(0x0D),
            "tab" => Some(0x09),
            "backspace" => Some(0x08),
            "escape" | "esc" => Some(0x1B),
            "shift" | "lshift" => Some(0x10),
            "rshift" => Some(0xA1),
            "ctrl" | "control" | "lctrl" => Some(0x11),
            "rctrl" => Some(0xA3),
            "alt" | "lalt" => Some(0x12),
            "ralt" => Some(0xA5),
            "up" | "arrowup" => Some(0x26),
            "down" | "arrowdown" => Some(0x28),
            "left" | "arrowleft" => Some(0x25),
            "right" | "arrowright" => Some(0x27),
            "delete" => Some(0x2E),
            "insert" => Some(0x2D),
            "home" => Some(0x24),
            "end" => Some(0x23),
            "pageup" => Some(0x21),
            "pagedown" => Some(0x22),
            "f1" => Some(0x70),
            "f2" => Some(0x71),
            "f3" => Some(0x72),
            "f4" => Some(0x73),
            "f5" => Some(0x74),
            "f6" => Some(0x75),
            "f7" => Some(0x76),
            "f8" => Some(0x77),
            "f9" => Some(0x78),
            "f10" => Some(0x79),
            "f11" => Some(0x7A),
            "f12" => Some(0x7B),
            _ => None,
        }
    }
}
